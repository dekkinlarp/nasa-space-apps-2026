import { useStore } from "../store";
import { fmtLonLat, fmtNum } from "../format";
import type { AreaData } from "../types";

const center = (a: AreaData): [number, number] => {
  const g = a.layers.grid;
  return [(g.west + g.east) / 2, (g.south + g.north) / 2];
};
const km = (a: AreaData) => ((a.layers.grid.width * a.layers.grid.cellSizeM) / 1000).toFixed(1);
const fmtLatLonShort = ([lon, lat]: [number, number]) => `${Math.abs(lat).toFixed(3)}°${lat < 0 ? "S" : "N"} ${lon.toFixed(3)}°E`;

export function TopBar() {
  const area = useStore((s) => s.area);
  const engine = useStore((s) => s.engine);
  const c = area?.conditions;
  const radiation = c?.radiationMSvPerDay ?? null;
  return (
    <header className="topbar">
      <div className="brand">
        <svg width="26" height="26" viewBox="0 0 26 26" aria-hidden>
          <circle cx="13" cy="13" r="11" fill="none" stroke="var(--accent)" strokeWidth="2" />
          <path d="M5 16 L10 10 L14 14 L17 11 L21 16" fill="none" stroke="var(--accent)" strokeWidth="1.8" strokeLinejoin="round" />
        </svg>
        <div>
          <div className="brand-title">MARTIAN MAP</div>
          <div className="brand-sub">EVA planner</div>
        </div>
      </div>
      <div className="site">
        <div className="site-name">{area?.config.area?.name ?? "Gale Crater boxwork"}</div>
        {area && (
          <div
            className="site-sub"
            title={`Centre ${fmtLonLat(center(area))} · ${km(area)} km square map · ${area.layers.grid.cellSizeM} m grid`}
          >
            {fmtLatLonShort(center(area))} · {km(area)} km · {area.layers.grid.cellSizeM} m grid
          </div>
        )}
      </div>
      {area?.synthetic && <div className="badge warn" title="data/fixture is generated by apps/web/scripts/make-fixture.ts">SYNTHETIC TEST DATA</div>}
      <div className="conditions">
        {c ? (
          <>
            <div className="cond">
              <div className="cond-k">Air</div>
              <div className="cond-v">
                {fmtNum(c.tempMinC, 0)} to {fmtNum(c.tempMaxC, 0, "°C")}
              </div>
            </div>
            {(c.sunrise || c.sunset) && (
              <div className="cond">
                <div className="cond-k">Daylight</div>
                <div className="cond-v" title="Local mean solar time (LMST)">
                  {c.sunrise ?? "?"}–{c.sunset ?? "?"}
                </div>
              </div>
            )}
            {radiation != null && (
              <div className="cond">
                <div className="cond-k">Radiation</div>
                <div className="cond-v">{radiation.toFixed(2)} mSv/sol</div>
              </div>
            )}
            <div
              className="cond-note"
              title={[
                "Typical values for this site, not a live forecast.",
                c.observed ? `Curiosity REMS (air) and RAD (radiation), ${c.observed}.` : "From Curiosity REMS (air) and RAD (radiation).",
                c.source ?? "",
              ]
                .filter(Boolean)
                .join("\n")}
            >
              Typical conditions <span aria-hidden>ⓘ</span>
            </div>
          </>
        ) : (
          <div className="cond-note" title="No conditions.json for this area">
            No conditions data
          </div>
        )}
      </div>
      <div className={`engine-dot ${engine.ready ? "ok" : engine.error ? "bad" : ""}`} title={engine.error ?? (engine.ready ? "Routing core ready" : "Loading routing core…")} />
    </header>
  );
}
