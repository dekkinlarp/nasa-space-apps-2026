import { useStore } from "../store";
import { fmtLonLat, fmtNum } from "../format";
import { SidebarIcon } from "./icons";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Spinner } from "@/components/ui/spinner";
import { cn } from "@/lib/utils";

/** Which site this is. Sits at the top of the side panel. */
export function SiteHeader({ onCollapse }: { onCollapse: () => void }) {
  const area = useStore((s) => s.area);
  const engine = useStore((s) => s.engine);
  const g = area?.manifest.grid;
  const name = area?.config.area?.name ?? "Gale Crater boxwork";
  return (
    <>
    {/* On the bottom sheet the header is one line: where this is, and whether the data is real. */}
    <div className="hidden flex-none items-center gap-2 pt-2 pr-[max(var(--gutter),env(safe-area-inset-right))] pl-[max(var(--gutter),env(safe-area-inset-left))] text-base sheet:flex sheet:in-[.sheet-closed]:hidden">
      <span className="truncate font-semibold">{name}</span>
      {area?.synthetic && (
        <Badge variant="warning" className="flex-none">
          Synthetic test data
        </Badge>
      )}
    </div>
    <header className="site-head flex-none px-4 pt-3 pb-3 sheet:hidden">
      <div className="flex min-h-7 items-center gap-2">
        <span className="text-sm font-medium text-ink-2">EVAres</span>
        {/* Routing is ready almost always, so only the exceptions are shown. */}
        {!engine.ready && (
          <span className={cn("ml-auto flex items-center gap-1.5 text-xs", engine.error ? "text-bad" : "text-muted-foreground")} role="status">
            {!engine.error && <Spinner className="size-3" />}
            {engine.error ? "Routing unavailable" : "Loading routing"}
          </span>
        )}
        {/* Same box and icon size as the button that brings the panel back (App.tsx), so the control does not change size when toggled. */}
        <Button variant="ghost" size="icon-lg" className={cn("-my-1 -mr-2 text-ink-2 coarse:size-11", engine.ready && "ml-auto")} aria-label="Hide sidebar" title="Hide sidebar" aria-expanded onClick={onCollapse}>
          <SidebarIcon on />
        </Button>
      </div>
      <h1 className="mt-2 mb-1.5 text-2xl font-bold tracking-[-0.022em]">{name}</h1>
      {g && (
        <div className="text-sm text-muted-foreground">
          {fmtLonLat([(g.west + g.east) / 2, (g.south + g.north) / 2])} · {g.width === g.height ? `${((g.width * g.cellSizeM) / 1000).toFixed(0)} km square` : `${((g.width * g.cellSizeM) / 1000).toFixed(0)} × ${((g.height * g.cellSizeM) / 1000).toFixed(0)} km`}
        </div>
      )}
      <ConditionsLine className="mt-0.5" />
      {area?.synthetic && (
        <Badge variant="warning" className="mt-2" title="data/fixture is generated by apps/web/scripts/make-fixture.ts">
          Synthetic test data
        </Badge>
      )}
    </header>
    </>
  );
}

/** A true minus sign, so temperatures read like the numbers on the profile axis. */
const minus = (s: string) => s.replace(/-/g, "−");

/**
 * The conditions a walk has to plan around, as one line of site facts. They are typical values from
 * Curiosity's weather and radiation instruments, not live readings, and the line says so.
 */
export function ConditionsLine({ className }: { className?: string }) {
  const c = useStore((s) => s.area?.conditions);
  if (!c) return null;
  const parts = [
    minus(`${fmtNum(c.tempMinC, 0)} to ${fmtNum(c.tempMaxC, 0, " °C")}`),
    (c.sunrise || c.sunset) && `daylight ${c.sunrise ?? "?"}–${c.sunset ?? "?"}`,
    c.radiationMSvPerDay != null && `${c.radiationMSvPerDay.toFixed(2)} mSv/sol`,
  ].filter(Boolean);
  const source = [`${c.observed ? `REMS/RAD, ${c.observed}` : "Curiosity REMS/RAD"}. Daylight is local mean solar time.`, c.source].filter(Boolean).join("\n");
  return (
    <div className={cn("text-sm text-muted-foreground", className)} title={source}>
      Typical sol: {parts.join(", ")}
    </div>
  );
}
