import type { ReactNode } from "react";
import { useStore } from "../store";
import { fmtLonLat, fmtNum } from "../format";
import { SidebarIcon } from "./icons";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Panel } from "@/components/ui/panel";
import { cn } from "@/lib/utils";

/** Which site this is. Sits at the top of the side panel. */
export function SiteHeader({ onCollapse }: { onCollapse: () => void }) {
  const area = useStore((s) => s.area);
  const engine = useStore((s) => s.engine);
  const g = area?.manifest.grid;
  const status = engine.ready ? "ok" : engine.error ? "bad" : "busy";
  return (
    <header className="site-head flex-none px-4 pt-4 pb-3 sheet:hidden">
      <div className="flex min-h-6 items-center gap-2 text-muted-foreground">
        <span className="caps">Martian Map · EVA planner</span>
        <span
          className={cn("ml-auto flex items-center gap-1.5", status === "bad" && "text-bad")}
          title={engine.error ?? (engine.ready ? "Routing core ready" : "Loading routing core…")}
        >
          <i className={cn("size-1.5 rounded-full", status === "ok" ? "bg-ok" : status === "bad" ? "bg-bad" : "bg-warn")} />
          <span className="caps">{engine.ready ? "Ready" : engine.error ? "Routing error" : "Loading"}</span>
        </span>
        <Button variant="ghost" size="icon-xs" className="-mr-1 text-ink-2" aria-label="Hide sidebar" title="Hide sidebar" aria-expanded onClick={onCollapse}>
          <SidebarIcon on />
        </Button>
      </div>
      <h1 className="mt-3 mb-1.5 text-2xl font-bold tracking-[-0.022em]">{area?.config.area?.name ?? "Gale Crater boxwork"}</h1>
      {g && (
        <div className="text-sm text-muted-foreground">
          {fmtLonLat([(g.west + g.east) / 2, (g.south + g.north) / 2])} · {g.width === g.height ? `${((g.width * g.cellSizeM) / 1000).toFixed(0)} km square` : `${((g.width * g.cellSizeM) / 1000).toFixed(0)} × ${((g.height * g.cellSizeM) / 1000).toFixed(0)} km`} · {g.cellSizeM} m grid
        </div>
      )}
      {area?.synthetic && (
        <Badge variant="warning" className="mt-2" title="data/fixture is generated by apps/web/scripts/make-fixture.ts">
          Synthetic test data
        </Badge>
      )}
    </header>
  );
}

/** The conditions a walk has to plan around. Floats over the top of the map, out of the side panel. */
export function ConditionsBar() {
  const c = useStore((s) => s.area?.conditions);
  if (!c) return null;
  const radiation = c.radiationMSvPerDay ?? null;
  const note = `${c.observed ? `REMS/RAD, ${c.observed}` : "Curiosity REMS/RAD"} · typical values, not live`;
  return (
    <Panel render={<dl />} className="m-0 flex h-11 min-w-0 items-center overflow-hidden px-1" title={[note, c.source].filter(Boolean).join("\n")}>
      <Condition label="Air">
        {fmtNum(c.tempMinC, 0)} to {fmtNum(c.tempMaxC, 0, "°C")}
      </Condition>
      {(c.sunrise || c.sunset) && (
        <Condition label="Daylight" title="Local mean solar time (LMST)">
          {c.sunrise ?? "?"}–{c.sunset ?? "?"}
        </Condition>
      )}
      {radiation != null && <Condition label="Radiation">{radiation.toFixed(2)} mSv/sol</Condition>}
      <Condition label="Source" className="text-muted-foreground compact:hidden">
        Typical, not live
      </Condition>
    </Panel>
  );
}

/** One reading in the conditions bar. Phones keep the first two. */
function Condition({ label, title, className, children }: { label: string; title?: string; className?: string; children: ReactNode }) {
  return (
    <div className={cn("min-w-0 border-l px-3 first:border-l-0 sheet:px-2.5 phone:nth-[n+3]:hidden", className)} title={title}>
      <dt className="caps text-[10px] text-muted-foreground">{label}</dt>
      <dd className="m-0 mt-px text-sm whitespace-nowrap">{children}</dd>
    </div>
  );
}
