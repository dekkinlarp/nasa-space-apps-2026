import { useStore } from "../store";
import { fmtLonLat, fmtNum } from "../format";
import { SidebarIcon } from "./icons";

/** Which site this is. Sits at the top of the side panel. */
export function SiteHeader({ onCollapse }: { onCollapse: () => void }) {
  const area = useStore((s) => s.area);
  const engine = useStore((s) => s.engine);
  const g = area?.layers.grid;
  const status = engine.ready ? "ok" : engine.error ? "bad" : "busy";
  return (
    <header className="site-head">
      <div className="site-top">
        <span className="label product">Martian Map · EVA planner</span>
        <span className={`engine ${status}`} title={engine.error ?? (engine.ready ? "Routing core ready" : "Loading routing core…")}>
          <i />
          <span className="label">{engine.ready ? "Ready" : engine.error ? "Routing error" : "Loading"}</span>
        </span>
        <button className="icon-btn sidebar-toggle" aria-label="Hide sidebar" title="Hide sidebar" aria-expanded onClick={onCollapse}>
          <SidebarIcon on />
        </button>
      </div>
      <h1 className="site-name">{area?.config.area?.name ?? "Gale Crater boxwork"}</h1>
      {g && (
        <div className="site-meta">
          {fmtLonLat([(g.west + g.east) / 2, (g.south + g.north) / 2])} · {((g.width * g.cellSizeM) / 1000).toFixed(0)} km square · {g.cellSizeM} m grid
        </div>
      )}
      {area?.synthetic && (
        <span className="badge warn" title="data/fixture is generated by apps/web/scripts/make-fixture.ts">
          Synthetic test data
        </span>
      )}
    </header>
  );
}

/** The conditions a walk has to plan around. Floats over the top of the map, out of the side panel. */
export function ConditionsBar() {
  const c = useStore((s) => s.area?.conditions);
  if (!c) return null;
  const radiation = c.radiationMSvPerDay ?? null;
  const note = `${c.observed ? `REMS/RAD, ${c.observed}` : "Curiosity REMS/RAD"} · typical values, not live`;
  return (
    <dl className="conditions glass" title={[note, c.source].filter(Boolean).join("\n")}>
      <div className="cond">
        <dt className="label">Air</dt>
        <dd>
          {fmtNum(c.tempMinC, 0)} to {fmtNum(c.tempMaxC, 0, "°C")}
        </dd>
      </div>
      {(c.sunrise || c.sunset) && (
        <div className="cond" title="Local mean solar time (LMST)">
          <dt className="label">Daylight</dt>
          <dd>
            {c.sunrise ?? "?"}–{c.sunset ?? "?"}
          </dd>
        </div>
      )}
      {radiation != null && (
        <div className="cond">
          <dt className="label">Radiation</dt>
          <dd>{radiation.toFixed(2)} mSv/sol</dd>
        </div>
      )}
      <div className="cond cond-src">
        <dt className="label">Source</dt>
        <dd>Typical, not live</dd>
      </div>
    </dl>
  );
}
