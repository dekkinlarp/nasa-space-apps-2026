import { useStore } from "../store";
import { fmtLonLat, fmtNum } from "../format";

export function TopBar() {
  const area = useStore((s) => s.area);
  const engine = useStore((s) => s.engine);
  const c = area?.conditions;
  const radiation = c?.radiationMSvPerDay ?? null;
  return (
    <header className="topbar">
      <div className="brand">
        <svg width="26" height="26" viewBox="0 0 26 26" aria-hidden>
          <circle cx="13" cy="13" r="11" fill="none" stroke="var(--accent)" strokeWidth="2" />
          <path d="M5 16 L10 10 L14 14 L17 11 L21 16" fill="none" stroke="var(--accent)" strokeWidth="1.8" strokeLinejoin="round" />
        </svg>
        <div>
          <div className="brand-title">MARTIAN MAP</div>
          <div className="brand-sub">EVA planner</div>
        </div>
      </div>
      <div className="site">
        <div className="site-name">{area?.config.area?.name ?? "Gale Crater boxwork"}</div>
        <div className="site-sub mono">
          {area ? `${fmtLonLat([(area.layers.grid.west + area.layers.grid.east) / 2, (area.layers.grid.south + area.layers.grid.north) / 2])} · ${((area.layers.grid.width * area.layers.grid.cellSizeM) / 1000).toFixed(1)} km square, ${area.layers.grid.cellSizeM} m grid` : ""}
        </div>
      </div>
      {area?.synthetic && <div className="badge warn" title="data/fixture is generated by apps/web/scripts/make-fixture.ts">SYNTHETIC TEST DATA</div>}
      <div className="conditions">
        {c ? (
          <>
            <div className="cond">
              <div className="cond-k">Air temp</div>
              <div className="cond-v">
                {fmtNum(c.tempMinC, 0)} to {fmtNum(c.tempMaxC, 0, " °C")}
              </div>
            </div>
            {(c.sunrise || c.sunset) && (
              <div className="cond">
                <div className="cond-k">Daylight</div>
                <div className="cond-v">
                  {c.sunrise ?? "?"}–{c.sunset ?? "?"} <span className="dim small">LMST</span>
                </div>
              </div>
            )}
            {radiation != null && (
              <div className="cond">
                <div className="cond-k">Radiation</div>
                <div className="cond-v">{radiation.toFixed(2)} mSv/sol</div>
              </div>
            )}
            <div className="cond-note" title={c.source ?? ""}>
              {c.observed ? `REMS/RAD, ${c.observed}` : "Curiosity REMS/RAD"}
              <br />
              typical values, not live
            </div>
          </>
        ) : (
          <div className="cond-note">No conditions.json for this area</div>
        )}
      </div>
      <div className={`engine-dot ${engine.ready ? "ok" : engine.error ? "bad" : ""}`} title={engine.error ?? (engine.ready ? "Routing core ready" : "Loading routing core…")} />
    </header>
  );
}
