/**
 * Martian Map server: a thin API over local files.
 *   /api/health   liveness
 *   /api/areas    data folders that contain a layers.json
 *   /api/config   area, surface classes, walk params and POIs from config/
 *   /data/*       static files from data/ (Range + cache headers)
 * No live NASA calls: everything is read from disk. Handlers stay small so the same
 * routes could be moved to a Worker with R2/static assets behind /data.
 */
import { serve } from "@hono/node-server";
import { Hono } from "hono";
import { createReadStream } from "node:fs";
import { readFile, readdir, stat } from "node:fs/promises";
import { Readable } from "node:stream";
import { dirname, extname, join, normalize, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const DATA_DIR = join(ROOT, "data");
const CONFIG_DIR = join(ROOT, "config");
const PORT = Number(process.env.MARSMAP_API_PORT ?? 8787);
const DEFAULT_AREA = "gale-boxwork";

/** Used only when config/walk-params.json does not exist yet; the response says so. */
const FALLBACK_WALK_PARAMS = {
  baseSpeedMps: 1.0,
  maxSlopeDeg: 25,
  cautionSlopeDeg: 15,
  bodyMassKg: 80,
  suitMassKg: 120,
  gravity: 3.71,
  evaLimitS: 6 * 3600,
  energyBudgetKJ: 12000,
  reserveFraction: 0.2,
  stopDwellS: 20 * 60,
  radiationMSvPerDay: 0.67,
};

const MIME: Record<string, string> = {
  ".json": "application/json; charset=utf-8",
  ".geojson": "application/geo+json; charset=utf-8",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".png": "image/png",
  ".webp": "image/webp",
  ".f32": "application/octet-stream",
  ".u8": "application/octet-stream",
  ".bin": "application/octet-stream",
  ".txt": "text/plain; charset=utf-8",
};

async function readJson<T>(path: string): Promise<T | null> {
  try {
    return JSON.parse(await readFile(path, "utf8")) as T;
  } catch {
    return null;
  }
}

const app = new Hono();

app.use("*", async (c, next) => {
  await next();
  c.header("Access-Control-Allow-Origin", "*");
});

app.get("/api/health", (c) => c.json({ ok: true, time: new Date().toISOString() }));

app.get("/api/areas", async (c) => {
  let entries: string[] = [];
  try {
    entries = await readdir(DATA_DIR);
  } catch {
    /* no data folder yet */
  }
  const areas = [];
  for (const id of entries.sort()) {
    const manifest = await readJson<{ grid?: { id?: string }; generatedAt?: string }>(join(DATA_DIR, id, "layers.json"));
    if (!manifest) continue;
    areas.push({ id, generatedAt: manifest.generatedAt ?? null, synthetic: id === "fixture" });
  }
  const ids = areas.map((a) => a.id);
  const defaultArea = ids.includes(DEFAULT_AREA) ? DEFAULT_AREA : (ids[0] ?? null);
  return c.json({ areas, defaultArea });
});

app.get("/api/config", async (c) => {
  const [area, surface, walk, pois] = await Promise.all([
    readJson<unknown>(join(CONFIG_DIR, "area.json")),
    readJson<{ classes?: unknown[] }>(join(CONFIG_DIR, "surface-classes.json")),
    readJson<unknown>(join(CONFIG_DIR, "walk-params.json")),
    readJson<{ pois?: unknown[] } | unknown[]>(join(CONFIG_DIR, "pois.json")),
  ]);
  // walk-params.json may be the bare object or wrapped as { params: {...} }.
  const walkObj = walk && typeof walk === "object" && "params" in (walk as object) ? (walk as { params: unknown }).params : walk;
  return c.json({
    area,
    surfaceClasses: surface?.classes ?? [],
    walkParams: walkObj ?? FALLBACK_WALK_PARAMS,
    walkParamsSource: walkObj ? "config/walk-params.json" : "server fallback (config/walk-params.json missing)",
    pois: Array.isArray(pois) ? pois : (pois?.pois ?? []),
  });
});

app.get("/data/*", async (c) => {
  const rel = decodeURIComponent(c.req.path.slice("/data/".length));
  const full = normalize(join(DATA_DIR, rel));
  if (!full.startsWith(DATA_DIR + sep)) return c.text("Forbidden", 403);
  let info;
  try {
    info = await stat(full);
  } catch {
    return c.text("Not found", 404);
  }
  if (!info.isFile()) return c.text("Not found", 404);

  const etag = `W/"${info.size.toString(16)}-${Math.floor(info.mtimeMs).toString(16)}"`;
  const headers: Record<string, string> = {
    "Content-Type": MIME[extname(full).toLowerCase()] ?? "application/octet-stream",
    "Accept-Ranges": "bytes",
    // Data is regenerated by the pipeline; revalidate cheaply with the ETag.
    "Cache-Control": "public, max-age=60, must-revalidate",
    ETag: etag,
    "Last-Modified": info.mtime.toUTCString(),
  };
  if (c.req.header("If-None-Match") === etag) return new Response(null, { status: 304, headers });

  const range = c.req.header("Range");
  let start = 0;
  let end = info.size - 1;
  let status = 200;
  if (range) {
    const m = /^bytes=(\d*)-(\d*)$/.exec(range.trim());
    if (!m || (m[1] === "" && m[2] === "")) {
      return new Response(null, { status: 416, headers: { ...headers, "Content-Range": `bytes */${info.size}` } });
    }
    if (m[1] === "") {
      start = Math.max(0, info.size - Number(m[2]));
    } else {
      start = Number(m[1]);
      if (m[2] !== "") end = Math.min(end, Number(m[2]));
    }
    if (start > end || start >= info.size) {
      return new Response(null, { status: 416, headers: { ...headers, "Content-Range": `bytes */${info.size}` } });
    }
    status = 206;
    headers["Content-Range"] = `bytes ${start}-${end}/${info.size}`;
  }
  headers["Content-Length"] = String(end - start + 1);
  if (c.req.method === "HEAD") return new Response(null, { status, headers });
  const body = Readable.toWeb(createReadStream(full, { start, end })) as ReadableStream;
  return new Response(body, { status, headers });
});

serve({ fetch: app.fetch, port: PORT }, (info) => {
  console.log(`marsmap server on http://localhost:${info.port} (data: ${DATA_DIR})`);
});
